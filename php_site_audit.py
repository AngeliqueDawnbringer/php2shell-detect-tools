#!/usr/bin/env python3
"""DNS inventory and bounded PHP fingerprint crawler (Python 3.10+).
Install: python3 -m pip install requests dnspython
Run: python3 php_site_audit.py example.com www.example.com --output report.json
Or:  python3 php_site_audit.py --hosts-file hosts.txt --max-pages 50

Only explicit host:port pairs are crawled. Supply www/subdomains separately.
Bare names use HTTPS; use an explicit http:// URL for HTTP-only sites.
No exploitation, path guessing, form submission or JavaScript execution.
robots.txt is honoured; query links are skipped to limit crawl traps.
DNS records do not establish PHP usage. All remote fingerprints can be stale,
spoofed or generated by a proxy/static export. No vulnerability verdict is made.
"""
import argparse
from collections import deque
from datetime import datetime, timezone
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import time
from urllib.parse import urljoin, urlsplit, urlunsplit
from urllib.robotparser import RobotFileParser

try:
    import requests
    import dns.resolver
except ImportError:
    raise SystemExit('Install dependencies: python3 -m pip install requests dnspython')

UA = 'PHPInventoryBot/1.0'
PHP_VERSION = re.compile(r'\bPHP[/\s]+(\d+\.\d+(?:\.\d+)?(?:[-+._a-zA-Z0-9]*)?)', re.I)
PHP_PATH = re.compile(r'\.(?:php\d*|phtml|phps)(?:/|$)', re.I)
STATIC = re.compile(r'\.(?:jpg|jpeg|png|gif|svg|webp|pdf|zip|gz|mp4|mp3|woff2?|ico|css|js)$', re.I)


def normalise(value):
    p = urlsplit(value.strip() if '://' in value else 'https://' + value.strip())
    if p.scheme not in ('https', 'http') or not p.hostname or p.username or p.password:
        raise ValueError('Expected an HTTP(S) URL or hostname without credentials')
    host = p.hostname.encode('idna').decode().lower().rstrip('.')
    host = '[' + host + ']' if ':' in host else host
    port = p.port
    netloc = host + (f':{port}' if port else '')
    return urlunsplit((p.scheme.lower(), netloc, p.path or '/', p.query, ''))


def scope_key(url):
    p = urlsplit(url)
    # Permit http->https upgrades on standard ports, not arbitrary service ports.
    port = p.port or (443 if p.scheme == 'https' else 80)
    return p.hostname, 'web' if port in (80, 443) else port


class Page(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.links, self.refs, self.generators = [], [], []

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == 'a' and a.get('href'):
            self.links.append(a['href'])
        for name in ('href', 'src', 'action'):
            if a.get(name):
                self.refs.append(a[name])
        if tag == 'meta' and a.get('name', '').lower() == 'generator':
            self.generators.append(a.get('content', '')[:200])


def fingerprint(url, headers, cookie_names, page):
    found = []
    def add(kind, strength, evidence, version=None):
        item = dict(kind=kind, strength=strength, evidence=evidence[:300])
        if version:
            item['advertised_version'] = version
        if item not in found:
            found.append(item)
    for key in ('x-powered-by', 'server', 'x-generator'):
        value = headers.get(key, '')
        if re.search(r'\bPHP\b', value, re.I):
            versions = PHP_VERSION.findall(value)
            if versions:
                for version in versions:
                    add('php_header', 'strong', f'{key}: {value}', version)
            else:
                add('php_header', 'strong', f'{key}: {value}')
    for name in cookie_names:
        if name.lower() == 'phpsessid':
            add('php_session_cookie', 'moderate', name)
        elif name.lower() == 'laravel_session':
            add('php_framework_cookie', 'moderate', name)
    if PHP_PATH.search(urlsplit(url).path):
        add('php_url', 'moderate', url)
    for ref in page.refs:
        target = urljoin(url, ref)
        if scope_key(target) != scope_key(url):
            continue
        path = urlsplit(target).path
        if PHP_PATH.search(path):
            add('php_link', 'weak', path)
        if re.search(r'/(?:wp-content|wp-includes)/', path, re.I):
            add('wordpress_asset', 'weak', path)
    for generator in page.generators:
        if re.search(r'\b(?:WordPress|Drupal|Joomla|TYPO3)\b', generator, re.I):
            add('php_cms_generator', 'weak', generator)
    return found


def dns_inventory(host, timeout):
    resolver = dns.resolver.Resolver()
    resolver.lifetime = timeout
    result = {}
    for kind in ('A', 'AAAA', 'CNAME', 'NS', 'MX'):
        try:
            result[kind] = {'values': [str(r) for r in resolver.resolve(host, kind)]}
        except dns.exception.DNSException as exc:
            result[kind] = {'values': [], 'status': type(exc).__name__}
    return result


class Crawler:
    def __init__(self, args, seeds):
        self.args = args
        self.allowed = {scope_key(s) for s in seeds}
        self.session = requests.Session()
        self.session.headers['User-Agent'] = UA
        self.robots = {}
        self.last = 0

    def fetch(self, url, delay=None):
        time.sleep(max(0, (self.args.delay if delay is None else delay) - (time.monotonic() - self.last)))
        self.last = time.monotonic()
        # Never forward cookies between requests or store their values in reports.
        self.session.cookies.clear()
        with self.session.get(url, timeout=(self.args.timeout, self.args.timeout),
                              stream=True, allow_redirects=False) as response:
            raw = bytearray()
            truncated = False
            deadline = time.monotonic() + self.args.timeout
            for chunk in response.iter_content(16384):
                raw.extend(chunk)
                if len(raw) > self.args.max_bytes or time.monotonic() > deadline:
                    truncated = True
                    break
            body = bytes(raw[:self.args.max_bytes]).decode(response.encoding or 'utf-8', errors='replace')
            return response.status_code, dict((k.lower(), v) for k, v in response.headers.items()), list(response.cookies.keys()), body, truncated

    def policy(self, url):
        p = urlsplit(url)
        origin = f'{p.scheme}://{p.netloc}'
        if origin not in self.robots:
            rp = RobotFileParser()
            try:
                status, _, _, body, truncated = self.fetch(origin + '/robots.txt')
                if status in (404, 410):
                    rp.parse([])
                elif 200 <= status < 300 and not truncated:
                    rp.parse(body.splitlines())
                else:
                    raise ValueError(f'robots.txt status {status}, truncated={truncated}; crawl skipped')
                self.robots[origin] = (rp, None)
            except (requests.RequestException, ValueError) as exc:
                self.robots[origin] = (None, str(exc))
        return self.robots[origin]

    def crawl(self, seed):
        queue = deque([(seed, 0)])
        scheduled = {seed}
        pages = []
        while queue and len(pages) < self.args.max_pages:
            url, depth = queue.popleft()
            row = {'url': url, 'depth': depth}
            pages.append(row)
            rp, error = self.policy(url)
            if error or not rp.can_fetch(UA, url):
                row['skipped'] = error or 'robots.txt disallows this URL'
                continue
            try:
                delay = max(self.args.delay, rp.crawl_delay(UA) or 0)
                status, headers, cookies, body, truncated = self.fetch(url, delay)
                row.update(status=status, truncated=truncated)
                page = Page()
                if 'html' in headers.get('content-type', '').lower():
                    page.feed(body)
                row['fingerprints'] = fingerprint(url, headers, cookies, page)
                row['server'] = headers.get('server')
                links = []
                if status in (301, 302, 303, 307, 308) and headers.get('location'):
                    row['redirect'] = urljoin(url, headers['location'])
                    links.append(row['redirect'])
                elif 200 <= status < 300 and depth < self.args.max_depth:
                    links.extend(page.links)
                for link in links:
                    try:
                        raw_url = urljoin(url, link)
                        if urlsplit(raw_url).scheme not in ('http', 'https'):
                            continue
                        target = normalise(raw_url)
                        p = urlsplit(target)
                        if scope_key(target) not in self.allowed:
                            continue
                        if p.query or STATIC.search(p.path) or target in scheduled:
                            continue
                        if len(scheduled) >= self.args.max_pages:
                            break
                        scheduled.add(target)
                        queue.append((target, depth + 1))
                    except ValueError:
                        continue
            except (requests.RequestException, ValueError) as exc:
                row['error'] = str(exc)
        evidence = [f for p in pages for f in p.get('fingerprints', [])]
        versions = sorted({f['advertised_version'] for f in evidence if 'advertised_version' in f})
        strength = 'strong' if any(f['strength'] == 'strong' for f in evidence) else 'moderate' if any(f['strength'] == 'moderate' for f in evidence) else 'weak' if evidence else None
        return dict(seed=seed, php_assessment={'strong': 'PHP advertised', 'moderate': 'PHP indicated', 'weak': 'PHP ecosystem clues', None: 'PHP not detected'}[strength], advertised_versions=versions, pages=pages)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('targets', nargs='*')
    parser.add_argument('--hosts-file', type=Path, help='One hostname or URL per line; # comments accepted')
    parser.add_argument('--output', type=Path, default=Path('php-audit.json'))
    parser.add_argument('--max-pages', type=int, default=30, help='Maximum queued URLs per seed, including redirects')
    parser.add_argument('--max-depth', type=int, default=2)
    parser.add_argument('--delay', type=float, default=1.0)
    parser.add_argument('--timeout', type=float, default=10.0)
    parser.add_argument('--max-bytes', type=int, default=1048576)
    args = parser.parse_args()
    if args.max_pages < 1 or args.max_depth < 0 or args.delay < 0 or args.timeout <= 0 or args.max_bytes < 1:
        parser.error('Invalid limit: pages/bytes/timeout must be positive; depth/delay nonnegative')
    targets = list(args.targets)
    if args.hosts_file:
        targets += [s for line in args.hosts_file.read_text().splitlines() if (s := line.split('#', 1)[0].strip())]
    try:
        seeds = list(dict.fromkeys(normalise(t) for t in targets))
    except ValueError as exc:
        parser.error(str(exc))
    if not seeds:
        parser.error('Supply a target or --hosts-file')
    report = dict(timestamp_utc=datetime.now(timezone.utc).isoformat(), limitations=[
        'DNS does not detect PHP. No subdomain brute force or DNS zone transfer is performed.',
        'Versions are advertised claims, not verified installed versions or vulnerability findings.',
        'A hidden version or absent signal does not prove PHP is absent or patched.',
        'CMS assets can be static or stale. Only explicitly listed hosts/services are visited.',
        'robots.txt failures/redirects block crawling that origin; query links and JavaScript are not crawled.',
        'GET requests only; no forms submitted. GET endpoints can still have side effects.',
        'Request timeouts are best effort, not a strict overall runtime deadline.'
    ], dns={}, sites=[])
    crawler = Crawler(args, seeds)
    for host in sorted({urlsplit(s).hostname for s in seeds}):
        report['dns'][host] = dns_inventory(host, args.timeout)
    for seed in seeds:
        site = crawler.crawl(seed)
        report['sites'].append(site)
        print(f"{seed}: {site['php_assessment']}; advertised versions: {', '.join(site['advertised_versions']) or 'unknown'}")
    args.output.write_text(json.dumps(report, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    print(f'Report: {args.output}')


if __name__ == '__main__':
    main()
